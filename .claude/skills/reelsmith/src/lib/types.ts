export interface CaptionStyle {
  font: string;
  fontSize: number;
  position: "top" | "center" | "bottom";
  primaryColor: string; // ffmpeg/ASS &HBBGGRR& or #RRGGBB, converted in captions.ts
  outlineColor: string;
  outlinePx: number;
  uppercase: boolean;
  wordsPerCaption: number;
}

export interface Style {
  name: string;
  aspectRatio: "9:16" | "16:9" | "1:1" | "4:5";
  width: number;
  height: number;
  fps: number;
  pacing: "fast" | "medium" | "slow"; // hint passed into shot-prompt preamble
  voiceId: string; // default ElevenLabs voice id, per-shot can override
  shotPromptPreamble: string; // prepended to every shot prompt sent to the video model
  captions: CaptionStyle;
}

export type ShotEngine = "seedance" | "gemini";

export interface Shot {
  id: string;
  engine: ShotEngine;
  prompt: string;
  durationSeconds: number;
  /** Native audio / lip-synced dialogue generated by the video model itself (Seedance only). */
  nativeAudio?: boolean;
  /** Voiceover narrated by ElevenLabs and burned in as captions. Mutually exclusive in practice with nativeAudio. */
  voiceover?: {
    text: string;
    voiceId?: string; // overrides style.voiceId
  };
  /** Reference image paths for image-to-video, if the engine supports it. */
  referenceImages?: string[];
  /** Set true to force regeneration even if a cache hit exists. */
  forceRegenerate?: boolean;
}

export interface ProjectManifest {
  slug: string;
  style: string; // name of styles/<name>.json
}
